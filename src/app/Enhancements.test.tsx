import { beforeEach, describe, expect, it, vi } from 'vitest';
import { render, screen, within } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { App } from './App';

beforeEach(() => { window.history.replaceState(null, '', '/#/learn?path=math'); });
describe('学生向けの学習支援', () => {
  it('Emacsのモードと固定の実行手順を確認し、文書コードとは区別してコピーする', async () => {
    window.history.replaceState(null, '', '/#/japanese');
    const user = userEvent.setup(); const app = render(<App />);
    await screen.findByLabelText('日本語文書のLaTeX');
    await user.selectOptions(screen.getByRole('combobox', { name: '利用環境' }), 'linux');
    expect(screen.getByText('C-h m')).toBeVisible();
    await user.selectOptions(screen.getByLabelText('Emacsで使っているモード'), 'standard');
    expect(screen.getByText('C-c C-f')).toBeVisible();
    await user.selectOptions(screen.getByLabelText('Emacsで使っているモード'), 'auctex');
    expect(screen.getByText('C-c C-c')).toBeVisible();
    await user.selectOptions(screen.getByLabelText('使うLaTeXエンジン'), 'uplatex');
    await user.click(screen.getByText('ターミナルで実行する場合'));
    const clipboard = vi.spyOn(navigator.clipboard, 'writeText').mockResolvedValue();
    await user.click(screen.getByRole('button', { name: 'コマンドをコピー' }));
    expect(clipboard.mock.calls[0][0]).toContain('dvipdfmx report-uplatex.dvi');
    expect(clipboard.mock.calls[0][0]).toContain('-no-shell-escape -file-line-error');
    expect(screen.getByLabelText('日本語文書のLaTeX')).toHaveTextContent('\\documentclass[uplatex');
    await user.selectOptions(screen.getByRole('combobox', { name: '利用環境' }), 'windows');
    expect(screen.queryByLabelText('Emacsで使っているモード')).not.toBeInTheDocument();
    expect(screen.getByText(/拡張子が.tex.txtになっていないか/)).toBeVisible();
    expect(screen.getByLabelText('使うLaTeXエンジン')).toHaveValue('uplatex');
    expect(window.location.hash).toBe('#/japanese');
    expect(localStorage.length).toBe(0); expect(sessionStorage.length).toBe(0);
    app.unmount(); render(<App />);
    await user.selectOptions(screen.getByRole('combobox', { name: '利用環境' }), 'linux');
    expect(screen.getByLabelText('Emacsで使っているモード')).toHaveValue('unknown');
  });
  it('利用環境をページ間で共有し、保存・送信せず、起動時にリセットする', async () => {
    window.history.replaceState(null, '', '/#/search');
    const user = userEvent.setup();
    const storage = vi.spyOn(Storage.prototype, 'setItem'); const fetcher = vi.spyOn(globalThis, 'fetch');
    const app = render(<App />);
    await user.selectOptions(screen.getByRole('combobox', { name: '利用環境' }), 'linux');
    expect(window.location.hash).toBe('#/search');
    await user.click(screen.getByRole('link', { name: '直す' }));
    const guide = await screen.findByText('Linux / Emacsでの操作案内');
    await user.click(guide);
    expect(screen.getByText(/TeXモードとAUCTeXでは操作が異なる/)).toBeVisible();
    await user.click(screen.getByText('参照した資料'));
    expect(screen.getByRole('link', { name: /TeX Mode/ })).toHaveAttribute('rel', 'noopener noreferrer');
    await user.click(screen.getByText('資料・学習'));
    await user.click(screen.getByRole('link', { name: '日本語文書' }));
    expect(await screen.findByText('Linux / Emacsでの操作案内')).toBeInTheDocument();
    expect(screen.getByRole('combobox', { name: '利用環境' })).toHaveValue('linux');
    app.unmount(); render(<App />);
    expect(screen.getByRole('combobox', { name: '利用環境' })).toHaveValue('none');
    expect(screen.queryByText('Linux / Emacsでの操作案内')).not.toBeInTheDocument();
    expect(storage).not.toHaveBeenCalled(); expect(fetcher).not.toHaveBeenCalled();
  });
  it('環境を切り替えても質問・ソース・診断結果を保持する', async () => {
    window.history.replaceState(null, '', '/#/workspace');
    const user = userEvent.setup(); render(<App />);
    const question = await screen.findByLabelText('LaTeXで何がしたい・何が知りたいですか？');
    const source = screen.getByLabelText('確認するLaTeXソース');
    await user.click(screen.getByText('TeXを貼り付け・編集'));
    await user.type(question, '分数'); await user.type(source, 'x_1');
    await user.click(screen.getByRole('button', { name: '確認する' }));
    await user.selectOptions(screen.getByRole('combobox', { name: '利用環境' }), 'windows');
    await user.click(screen.getByText('Windows / TeX Liveでの操作案内'));
    expect(screen.getByText(/\.tex\.txtになっていないか/)).toBeVisible();
    expect(question).toHaveValue('分数'); expect(source).toHaveValue('x_1');
    expect(screen.getByRole('button', { name: '1行 2列を編集欄で確認' })).toBeEnabled();
    expect(window.location.hash).toBe('#/workspace');
    expect(screen.queryByText(/入力が変わりました/)).not.toBeInTheDocument();
  });
  it('その他エディタの案内に切り替えても文書エンジンと生成コードを保持する', async () => {
    window.history.replaceState(null, '', '/#/japanese');
    const user = userEvent.setup(); render(<App />);
    await user.selectOptions(await screen.findByLabelText('使うLaTeXエンジン'), 'uplatex');
    const code = screen.getByLabelText('日本語文書のLaTeX').textContent;
    await user.selectOptions(screen.getByRole('combobox', { name: '利用環境' }), 'other');
    await user.click(screen.getByText('その他のエディタでの操作案内'));
    expect(screen.getByText(/エディタとTeXの実行環境は別/)).toBeVisible();
    expect(screen.getByLabelText('使うLaTeXエンジン')).toHaveValue('uplatex');
    expect(screen.getByLabelText('日本語文書のLaTeX').textContent).toBe(code);
    await user.selectOptions(screen.getByRole('combobox', { name: '利用環境' }), 'none');
    expect(screen.queryByText('その他のエディタでの操作案内')).not.toBeInTheDocument();
  });
  it('自己チェックはページ間で保持し、回答には理由を示す', async () => {
    const user = userEvent.setup(); render(<App />);
    await user.click(await screen.findByRole('checkbox', { name: '本文と数式モードを分ける：確認した' }));
    expect(screen.getByText('1 / 4 確認済み')).toBeInTheDocument();
    await user.click(screen.getByText('資料・学習'));
    await user.click(screen.getByRole('link', { name: '日本語文書' }));
    await screen.findByLabelText('日本語文書のLaTeX');
    await user.click(screen.getByText('資料・学習'));
    await user.click(screen.getByRole('link', { name: '学習コース' }));
    await user.click(screen.getByRole('link', { name: '数式の書き方を身につける' }));
    expect(screen.getByRole('checkbox', { name: '本文と数式モードを分ける：確認した' })).toBeChecked();
    await user.click(screen.getByRole('radio', { name: 'x_ij' }));
    await user.click(screen.getByRole('button', { name: '答えと理由を確認' }));
    expect(screen.getByText('もう一度、理由を確認してみましょう。')).toBeInTheDocument();
    expect(screen.getByText(/複数文字の添字は波括弧で/)).toBeInTheDocument();
    await user.click(screen.getByRole('radio', { name: 'x_{ij}' }));
    expect(screen.queryByText('正解です。')).not.toBeInTheDocument();
    await user.click(screen.getByRole('button', { name: '答えと理由を確認' }));
    expect(screen.getByText('正解です。')).toBeInTheDocument();
  });
  it('共有リンクには回答や進捗を含めず、印刷を開始する', async () => {
    const user = userEvent.setup(); render(<App />);
    const clipboard = vi.spyOn(navigator.clipboard, 'writeText').mockResolvedValue();
    const print = vi.spyOn(window, 'print').mockImplementation(() => {});
    await user.click(await screen.findByRole('checkbox', { name: '本文と数式モードを分ける：確認した' }));
    await user.click(screen.getByRole('button', { name: 'コースのリンクをコピー' }));
    expect(clipboard).toHaveBeenCalledWith(`${window.location.origin}/#/learn?path=math`);
    await user.click(screen.getByRole('button', { name: '学習シートを印刷' }));
    expect(print).toHaveBeenCalledOnce();
  });
  it('進捗は保存・送信しない。新たな起動でリセットする', async () => {
    const storage = vi.spyOn(Storage.prototype, 'setItem'); const fetcher = vi.spyOn(globalThis, 'fetch');
    const user = userEvent.setup(); const app = render(<App />);
    await user.click(await screen.findByRole('checkbox', { name: '本文と数式モードを分ける：確認した' }));
    app.unmount(); render(<App />);
    expect(screen.getByText('0 / 4 確認済み')).toBeInTheDocument();
    expect(storage).not.toHaveBeenCalled(); expect(fetcher).not.toHaveBeenCalled();
  });
  it('日本語文書のエンジンと構成を切り替えてコピーする', async () => {
    window.history.replaceState(null, '', '/#/japanese');
    const user = userEvent.setup(); render(<App />);
    const main = within(screen.getByRole('main'));
    expect(await main.findByLabelText('日本語文書のLaTeX')).toHaveTextContent('\\documentclass[lualatex');
    await user.selectOptions(screen.getByLabelText('使うLaTeXエンジン'), 'uplatex');
    await user.selectOptions(screen.getByLabelText('レポートの構成'), 'lab');
    expect(main.getByLabelText('日本語文書のLaTeX')).toHaveTextContent('\\usepackage[dvipdfmx]{graphicx}');
    expect(main.getByLabelText('日本語文書のLaTeX')).toHaveTextContent('\\section{結果}');
    expect(main.getByLabelText('upLaTeX用latexmkrc')).toHaveTextContent('dvipdfmx');
    expect(screen.getByText('文書全体はプレビュー対象外')).toBeInTheDocument();
    const clipboard = vi.spyOn(navigator.clipboard, 'writeText').mockResolvedValue();
    await user.click(screen.getAllByRole('button', { name: 'コードをコピー' })[0]);
    expect(clipboard.mock.calls[0][0]).toContain('\\documentclass[uplatex');
  });
  it('レシピから診断へ渡し、診断での編集は履歴に含めない', async () => {
    window.history.replaceState(null, '', '/#/recipes/subscript');
    const user = userEvent.setup(); render(<App />);
    await user.selectOptions(await screen.findByLabelText('添字'), 'ij');
    await user.click(screen.getByRole('button', { name: '生成コードを診断する →' }));
    const input = await screen.findByRole('textbox'); expect(input).toHaveValue('\\[\nx_{ij}\n\\]');
    await user.clear(input); await user.type(input, 'PRIVATE_SOURCE');
    expect(JSON.stringify(window.history.state)).not.toContain('PRIVATE_SOURCE');
    await user.click(screen.getByRole('link', { name: '探す' }));
    await user.click(screen.getByRole('link', { name: '直す' }));
    expect(screen.getByRole('textbox')).toHaveValue('');
  });
  it('未知のコースIDでも公開済みのコースに案内する', async () => {
    window.history.replaceState(null, '', '/#/learn?path=unknown'); render(<App />);
    expect(await screen.findByRole('heading', { name: '日本語レポートを始める' })).toBeInTheDocument();
  });
});
